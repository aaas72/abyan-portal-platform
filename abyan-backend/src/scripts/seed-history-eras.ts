async function bootstrap() {
  const app = await NestFactory.createApplicationContext(AppModule);
  const historyService = app.get(HistoryService);

  const existingEras = await historyService.findAllEras();
  if (existingEras.length > 0) {
    for (const era of existingEras) {
      await historyService.deleteEra((era as any)._id.toString());
    }
    console.log('Deleted existing history eras.');
  }

  for (const era of historyErasData) {
    await historyService.createEra(era);
    console.log(`Created era: ${era.eraTitle}`);
  }

  await app.close();
  console.log('History eras seeding completed successfully.');
}
bootstrap();
